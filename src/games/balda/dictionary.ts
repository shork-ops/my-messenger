/**
 * The dictionary for «Балда».
 *
 * The plan is explicit that a word must not be "checked" by a regular expression or by whether
 * a page exists in a search engine. What it needs is a fixed list of nouns in an agreed form,
 * carried with the game so that two players on two devices agree on what counts as a word.
 *
 * The list below is a curated set of common Russian common nouns in the nominative singular,
 * or nominative plural for words that have no singular (очки, шахматы). It is deliberately
 * small and checked by hand rather than scraping a morphological dictionary wholesale:
 * OpenCorpora contains proper names, abbreviations, obsolete forms and every inflection, and a
 * game that accepts "абажуром" because the dictionary contains that form is a game nobody can
 * play against each other fairly.
 *
 * Limits of this list, stated rather than hidden: it is not exhaustive, some rare nouns are
 * missing, and a word absent here is refused even if it is real Russian. The version number is
 * part of the game: a saved game keeps the dictionary it was started with.
 */

export const DICTIONARY_VERSION = 1;

/** Letters a word may contain after normalisation. No й, ъ, ы? All are allowed. */
export const ALPHABET = "абвгдежзийклмнопрстуфхцчшщъыьэюя";

/**
 * Normalises a word the way the whole game will: lowercase, ё folded to е.
 *
 * The fold is done on input, on the board and in the index, so there is no path where "ёлка"
 * and "елка" are different words. The plan asks for exactly this and calls out that it must be
 * uniform - a normalisation applied in one place only is a bug that shows up once per game.
 */
export function normalise(word: string): string {
  return word.trim().toLocaleLowerCase("ru-RU").replace(/ё/g, "е");
}

