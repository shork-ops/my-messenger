/** Every allowed word, normalised, as a Set for constant-time lookup. */
let wordSet: Set<string> | null = null;

export function dictionary(): Set<string> {
  if (!wordSet) {
    wordSet = new Set(
      WORDS.split(/\s+/)
        .map((word) => word.trim())
        .filter((word) => word.length > 0)
        .map(normalise)
        .filter((word) => /^[а-я]+$/.test(word))
    );
  }
  return wordSet;
}

/** Whether a word is in the dictionary. Normalises its input first. */
/**
 * Letters that may not begin a Russian word.
 *
 * The list above is a plain word list, and a plain word list can contain a fragment that reads
 * like a word: "ьа" was accepted because it appeared in it. A word beginning with a soft sign
 * is not a word in any variant of this game.
 */
const NO_LEADING = new Set(["ь", "ъ", "ы"]);

const VOWELS = new Set("аеиоуыэюя".split(""));

export function isWord(word: string): boolean {
  const normalised = normalise(word);
  if (!dictionary().has(normalised)) return false;
  if (NO_LEADING.has(normalised[0])) return false;
  // A word made only of consonants is not a word in Russian either.
  return [...normalised].some((letter) => VOWELS.has(letter));
}

/** How many words the game recognises. Shown in the rules so nobody assumes it is complete. */
export function dictionarySize(): number {
  return dictionary().size;
}

/**
 * Whether the dictionary loaded at all.
 *
 * The plan is explicit: if the dictionary cannot be loaded, show a retry rather than start
 * accepting any word. This is the check the interface uses.
 */
export function dictionaryReady(): boolean {
  return dictionarySize() >= 1000;
}

/**
 * Every prefix of every word, so a search can stop as soon as the letters cannot spell anything.
 *
 * This is the difference between a usable game and a frozen tab. Walking every simple path on
 * a 5x5 board is thousands of paths per square, and doing that for 33 possible letters froze
 * the browser for minutes. With prefixes, a path dies the moment "абв" cannot start a word,
 * and the whole board is searched in a few milliseconds.
 */
let prefixSet: Set<string> | null = null;

export function prefixes(): Set<string> {
  if (!prefixSet) {
    prefixSet = new Set();
    for (const word of dictionary()) {
      for (let length = 1; length <= word.length; length += 1) {
        prefixSet.add(word.slice(0, length));
      }
    }
  }
  return prefixSet;
}

/** Whether more letters could still make this prefix into a word. */
export function isPrefix(text: string): boolean {
  return prefixes().has(text);
}

/** For tests and the rules screen: the list as an array. */
export function allWords(): string[] {
  return [...dictionary()].sort();
}
